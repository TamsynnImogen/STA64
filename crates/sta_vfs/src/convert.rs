//! Turn a mod folder (loose files plus root `*.fpq` / `*.zfs` archives) into
//! the file list of one `.sta` archive (EDT-08, `sta-archive convert`).
//!
//! - Loose files keep their paths; root `*.fpq`, `*.zfs` and `*.sta` files are
//!   unpacked instead of copied.
//! - FPQ entries go to the paths stored in the archive (`odf/system/x.odf` in
//!   FO's `ODF.fpq`), ZFS entries where Armada II keeps each type (`.odf` →
//!   `odf/`, `.tt` → `techtree/`, the rest at the root), and an existing
//!   `.sta`'s entries (whiteouts too) as they are.
//! - Where two sources give one path (ignoring case), the first wins in the
//!   order loose, `.sta`, FPQ, ZFS (archives of a kind in name order): the
//!   same priority the VFS mounts them with.
//! - Without a `manifest.toml`, one is generated from `info.ini`'s `[Mod]`
//!   section (`docs/STA_ARCHIVE.md`, "Manifest"); `info.ini` itself is kept.

use std::collections::BTreeMap;
use std::path::Path;

use crate::sta::{Kind, StaArchive};
use crate::sta_write::{Content, Item};
use crate::zfs::Zfs;

/// Where each file came from, for the report.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Report {
    pub loose: usize,
    pub from_sta: usize,
    pub from_fpq: usize,
    pub from_zfs: usize,
    /// Archive entries dropped because a higher source had the path.
    pub shadowed: usize,
    /// The manifest was generated from `info.ini` (or a bare default).
    pub generated_manifest: bool,
}

fn zfs_path(name: &str) -> String {
    match name.rsplit_once('.').map(|(_, e)| e.to_ascii_lowercase()) {
        Some(e) if e == "odf" => format!("odf/{name}"),
        Some(e) if e == "tt" => format!("techtree/{name}"),
        _ => name.to_owned(),
    }
}

fn is_archive(name: &str) -> bool {
    let l = name.to_ascii_lowercase();
    l.ends_with(".fpq") || l.ends_with(".zfs") || l.ends_with(".sta")
}

/// `[Mod]` keys of an `info.ini`, lower-cased keys.
fn ini_mod_section(text: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut in_mod = false;
    for line in text.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            in_mod = l.eq_ignore_ascii_case("[mod]");
        } else if in_mod && let Some((k, v)) = l.split_once('=') {
            let v = v.trim();
            let v = v.strip_prefix('"').and_then(|s| s.strip_suffix('"')).unwrap_or(v);
            out.insert(k.trim().to_ascii_lowercase(), v.to_owned());
        }
    }
    out
}

/// A mod id from a name: lower case, `a-z 0-9 - _`, others become `-`.
pub fn mod_id(name: &str) -> String {
    let mut id = String::new();
    for c in name.chars() {
        let c = c.to_ascii_lowercase();
        if c.is_ascii_alphanumeric() || c == '_' {
            id.push(c);
        } else if !id.ends_with('-') {
            id.push('-');
        }
    }
    let id = id.trim_matches('-').to_owned();
    if id.is_empty() { "mod".into() } else { id }
}

fn toml_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `manifest.toml` for a mod folder named `folder` with `info.ini` text (if any).
pub fn manifest_from_info(folder: &str, info_ini: Option<&str>) -> String {
    let ini = info_ini.map(ini_mod_section).unwrap_or_default();
    let name = ini.get("name").cloned().unwrap_or_else(|| folder.to_owned());
    let version = ini.get("version").cloned().unwrap_or_else(|| "0.0.0".into());
    let parent = ini.get("parentmod").filter(|p| !p.is_empty());
    let mut m = String::from("# Generated by sta-archive convert from info.ini.\n[mod]\n");
    m += &format!("id = {}\n", toml_str(&mod_id(folder)));
    m += &format!("name = {}\n", toml_str(&name));
    m += &format!("version = {}  # as info.ini states it; may not be semantic versioning\n", toml_str(&version));
    if let Some(d) = ini.get("description") {
        m += &format!("description = {}\n", toml_str(d));
    }
    if let Some(a) = ini.get("author") {
        let authors: Vec<String> = a.split(',').map(str::trim).filter(|s| !s.is_empty()).map(toml_str).collect();
        m += &format!("authors = [{}]\n", authors.join(", "));
    }
    m += &format!("kind = {}\n", toml_str(if parent.is_some() { "addon" } else { "standalone" }));
    if let Some(p) = parent {
        m += &format!("\n[dependencies]\n{} = \"*\"  # info.ini ParentMod = {}\n", toml_str(&mod_id(p)), toml_str(p));
    }
    m
}

enum Origin {
    Loose(std::path::PathBuf),
    Sta(usize, usize),
    Fpq(usize, usize),
    Zfs(usize, usize),
    Whiteout,
    Manifest,
}

/// A mod folder planned for packing: which source gives each path. Files are
/// read only when [`ModFolder::items`]' loaders run (inside
/// `sta_write::pack_to`), so a mod of any size converts with about one file in
/// memory beside its FPQ/ZFS archives.
pub struct ModFolder {
    stas: Vec<StaArchive>,
    fpqs: Vec<sta_fpq::Fpq>,
    zfss: Vec<Zfs>,
    manifest: Vec<u8>,
    plan: Vec<(String, Origin)>,
    pub report: Report,
}

impl ModFolder {
    pub fn open(dir: &Path) -> Result<ModFolder, String> {
        let err = |p: &Path, e: &dyn std::fmt::Display| format!("{}: {e}", p.display());
        let mut report = Report::default();
        let mut plan: BTreeMap<String, (String, Origin)> = BTreeMap::new(); // key -> (path, origin)
        let add = |plan: &mut BTreeMap<String, (String, Origin)>, path: String, origin: Origin| -> bool {
            let key = path.to_ascii_lowercase();
            if plan.contains_key(&key) {
                return false;
            }
            plan.insert(key, (path, origin));
            true
        };

        // Loose files, minus the root archives.
        let mut archives: Vec<std::path::PathBuf> = Vec::new();
        let mut stack = vec![dir.to_path_buf()];
        while let Some(d) = stack.pop() {
            for e in std::fs::read_dir(&d).map_err(|e| err(&d, &e))? {
                let e = e.map_err(|e| err(&d, &e))?;
                let p = e.path();
                let ft = e.file_type().map_err(|e| err(&p, &e))?;
                if ft.is_dir() {
                    stack.push(p);
                } else if ft.is_file() {
                    let rel = p.strip_prefix(dir).unwrap().to_string_lossy().replace('\\', "/");
                    if d == dir && is_archive(&rel) {
                        archives.push(p);
                        continue;
                    }
                    add(&mut plan, rel, Origin::Loose(p));
                    report.loose += 1;
                }
            }
        }
        archives.sort();
        let ext = |p: &Path| p.extension().map(|x| x.to_string_lossy().to_ascii_lowercase()).unwrap_or_default();

        let mut stas = Vec::new();
        for p in archives.iter().filter(|p| ext(p) == "sta") {
            let a = StaArchive::open(p).map_err(|e| err(p, &e))?;
            for (i, e) in a.entries().iter().enumerate() {
                let o = if e.kind == Kind::Whiteout { Origin::Whiteout } else { Origin::Sta(stas.len(), i) };
                if add(&mut plan, e.path.clone(), o) {
                    report.from_sta += 1;
                } else {
                    report.shadowed += 1;
                }
            }
            stas.push(a);
        }
        let mut fpqs = Vec::new();
        for p in archives.iter().filter(|p| ext(p) == "fpq") {
            let f = sta_fpq::Fpq::open(p).map_err(|e| err(p, &e))?;
            for i in 0..f.len() {
                let path = f.path(i).map_err(|e| err(p, &e))?;
                if add(&mut plan, path, Origin::Fpq(fpqs.len(), i)) {
                    report.from_fpq += 1;
                } else {
                    report.shadowed += 1;
                }
            }
            fpqs.push(f);
        }
        let mut zfss = Vec::new();
        for p in archives.iter().filter(|p| ext(p) == "zfs") {
            let z = Zfs::open(p).map_err(|e| err(p, &e))?;
            for i in 0..z.len() {
                if add(&mut plan, zfs_path(&z.entry(i).name), Origin::Zfs(zfss.len(), i)) {
                    report.from_zfs += 1;
                } else {
                    report.shadowed += 1;
                }
            }
            zfss.push(z);
        }

        let mut manifest = Vec::new();
        if !plan.contains_key("manifest.toml") {
            let info = match plan.get("info.ini") {
                Some((_, Origin::Loose(p))) => std::fs::read(p).ok().map(|b| String::from_utf8_lossy(&b).into_owned()),
                _ => None,
            };
            let folder = dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_else(|| "mod".into());
            manifest = manifest_from_info(&folder, info.as_deref()).into_bytes();
            plan.insert("manifest.toml".into(), ("manifest.toml".into(), Origin::Manifest));
            report.generated_manifest = true;
        }
        Ok(ModFolder { stas, fpqs, zfss, manifest, plan: plan.into_values().collect(), report })
    }

    pub fn len(&self) -> usize {
        self.plan.len()
    }

    pub fn is_empty(&self) -> bool {
        self.plan.is_empty()
    }

    /// The items for `sta_write::pack_to`, each loaded only when written.
    pub fn items(&self) -> Vec<(String, Item<'_>)> {
        let fail = |e: String| std::io::Error::other(e);
        self.plan
            .iter()
            .map(|(path, o)| {
                let item = match o {
                    Origin::Whiteout => Item::Whiteout,
                    Origin::Manifest => Item::Data(self.manifest.clone()),
                    Origin::Loose(p) => {
                        let p = p.clone();
                        Item::Load(Box::new(move || std::fs::read(p)))
                    }
                    Origin::Sta(a, i) => Item::Load(Box::new(move || self.stas[*a].read(*i).map_err(|e| fail(e.to_string())))),
                    Origin::Fpq(a, i) => Item::Load(Box::new(move || self.fpqs[*a].read(*i).map_err(|e| fail(e.to_string())))),
                    Origin::Zfs(a, i) => Item::Load(Box::new(move || self.zfss[*a].read(*i).map_err(|e| fail(e.to_string())))),
                };
                (path.clone(), item)
            })
            .collect()
    }

    /// Every file read now (small mods and tests).
    pub fn files(&self) -> Result<Vec<(String, Content)>, String> {
        self.items()
            .into_iter()
            .map(|(p, i)| {
                let c = match i {
                    Item::Data(d) => Content::Data(d),
                    Item::Load(f) => Content::Data(f().map_err(|e| format!("{p}: {e}"))?),
                    Item::Whiteout => Content::Whiteout,
                };
                Ok((p, c))
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_from_info_ini() {
        let ini = "[Mod]\nName=Fleet Operations\nDescription=Stock \"FO\"\nAuthor=DOCa Cola, Optec\nVersion=4.0Z\nParentMod=\"STA2 Classic Mod\"\n";
        let m = manifest_from_info("Fleet Ops 4.0", Some(ini));
        assert!(m.contains("id = \"fleet-ops-4-0\""), "{m}");
        assert!(m.contains("name = \"Fleet Operations\""));
        assert!(m.contains("description = \"Stock \\\"FO\\\"\""));
        assert!(m.contains("authors = [\"DOCa Cola\", \"Optec\"]"));
        assert!(m.contains("version = \"4.0Z\""));
        assert!(m.contains("kind = \"addon\""));
        assert!(m.contains("\"sta2-classic-mod\" = \"*\""));
        let bare = manifest_from_info("My Mod!", None);
        assert!(bare.contains("id = \"my-mod\"") && bare.contains("kind = \"standalone\"") && !bare.contains("[dependencies]"));
    }

    #[test]
    fn loose_beats_packed_and_archives_unpack() {
        let d = std::env::temp_dir().join(format!("sta_convert_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(d.join("odf/system")).unwrap();
        std::fs::write(d.join("info.ini"), "[Mod]\nName=T\n").unwrap();
        std::fs::write(d.join("odf/system/a.odf"), "loose a").unwrap();
        let fpq = sta_fpq::write::write(
            2,
            &[("odf/system/a.odf".into(), b"packed a".to_vec()), ("odf/system/b.odf".into(), b"packed b".to_vec())],
            sta_fpq::write::Compression::Auto,
        )
        .unwrap();
        std::fs::write(d.join("ODF.fpq"), fpq).unwrap();
        let zfs = crate::zfs::write(&[crate::zfs::ZfsFile { name: "c.odf".into(), data: b"zfs c".to_vec(), time: 0 }, crate::zfs::ZfsFile { name: "t1.tt".into(), data: b"tt".to_vec(), time: 0 }], 0x1234_5678).unwrap();
        std::fs::write(d.join("assets.zfs"), zfs).unwrap();
        let m = ModFolder::open(&d).unwrap();
        let (files, r) = (m.files().unwrap(), m.report.clone());
        let get = |p: &str| files.iter().find(|(f, _)| f == p).map(|(_, c)| c.clone());
        assert_eq!(get("odf/system/a.odf"), Some(Content::Data(b"loose a".to_vec())));
        assert_eq!(get("odf/system/b.odf"), Some(Content::Data(b"packed b".to_vec())));
        assert_eq!(get("odf/c.odf"), Some(Content::Data(b"zfs c".to_vec())));
        assert_eq!(get("techtree/t1.tt"), Some(Content::Data(b"tt".to_vec())));
        assert!(get("ODF.fpq").is_none() && get("assets.zfs").is_none());
        assert!(get("manifest.toml").is_some() && get("info.ini").is_some());
        assert_eq!(r, Report { loose: 2, from_sta: 0, from_fpq: 1, from_zfs: 2, shadowed: 1, generated_manifest: true });
        let _ = std::fs::remove_dir_all(d);
    }
}

/// The value for a key, 0 when the tool does not know the opcode.
pub(crate) fn vex_op(kind: u32, map: u32, pp: u32, w: u32, ll: u32, vv: u32, op: u32) -> u8 {
    let k = (((((kind * 8 + map) * 4 + pp) * 2 + w) * 4 + ll) * 2 + vv) * 256 + op;
    match VEX_OPS.binary_search_by(|&(a, b, _)| {
        if k < a {
            std::cmp::Ordering::Greater
        } else if k > b {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => VEX_OPS[i].2,
        Err(_) => 0,
    }
}

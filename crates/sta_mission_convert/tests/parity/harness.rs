//! The parity harness (LUA-15f, step S8): the reference the Python converters wrote, loaded,
//! checked for staleness, and compared byte for byte with what the Rust converter produces.
//!
//! # For the lifter rows (LUA-15g, 15h, 15e)
//!
//! ```ignore
//! let Some(reference) = harness::obtain_or_skip() else { return };      // None: skipped, said why
//! let install = reference.install(Kind::Armada2).expect("no Armada II in the reference");
//! // `produced`: relative path in the reference layout -> the Rust converter's bytes.
//! let produced: BTreeMap<String, Vec<u8>> = ...;   // "missions/<name>.lua", "drl/missions/<name>.lua"
//! install.compare_all(&produced).assert_ok("a2");  // panics with counts, indices and line numbers
//! ```
//!
//! - [`obtain_or_skip`] returns the shared [`Reference`] (see [`obtain`] for where it comes from).
//! - [`RefInstall::files`] lists the reference's files sorted by relative path, `/`-separated:
//!   `missions/<stem>.lua` (Armada I and II), `drl/missions/<stem>.lua` (Armada II scaffolds).
//!   The position in that list is the file's *index in the run*; messages name only that index
//!   and the line number, never a file name or content (those are install-derived).
//! - [`RefInstall::compare`] checks one file ([`Verdict`]), [`RefInstall::compare_all`] a whole
//!   output, [`RefInstall::compare_subset`] a part of it (a closure over the relative path: a
//!   prefix such as `drl/`, a list of missions); reference files outside the subset are not
//!   missing and output files outside it are not extra. [`Report::assert_ok`] panics with counts
//!   only. `Debug` of `Verdict` and `Report` shows indices, lines and counts, never text.
//! - [`RefInstall::listing`] reads an objdump listing the reference wrote with
//!   `--objdump-listings`. LUA-15b's own gated test compares listings (its WORKPLAN row), so no
//!   listing comparison lives here.
//!
//! # The scratch detail file holds game text
//!
//! On a failure `assert_ok` writes `target/scratch/parity-<label>.txt`: install file names and
//! the differing lines of the reference and of the output. That is game content. It is for the
//! developer's eyes only (`/target` is git-ignored); never commit it, attach it to an issue or
//! a PR, or paste it anywhere. The same holds for a generated reference (next section).
//!
//! # What is compared
//!
//! Every byte, with one tolerance: in the header (line 1) the tool token. The Python emits
//!
//! ```text
//! -- <mission>: converted by tools/<x>_to_lua.py (LUA-nn) from <file>[ and <file>].
//! -- <mission>: rule scaffold generated by tools/drl_to_lua.py (LUA-07).
//! ```
//!
//! The Rust port names its own tool, so the Rust header must be
//! `-- <mission>: converted by <token> (<text>)` (or `rule scaffold generated by`) followed by the
//! reference's tail from the first `)` on, `<token>` without whitespace, the same mission name
//! and the same tail (` from <file>...` and the final dot) as the reference, ending in `\n` alone: no BOM,
//! no CRLF. A differing mission name, source file name or tail is a difference on line 1. The
//! Python writes no date, path or version into its output; its own constant text does name
//! `tools/dsl_to_lua.py` once more in a body comment of the mission files, and that line must
//! be equal like any other: the port copies it.
//!
//! # Where the reference comes from, and its lifetime
//!
//! See [`obtain`]: a stored reference (`STA64_TEST_LUA_REFERENCE`) or one the harness generates
//! (about 40 s) into a deterministic directory under the system temp dir, reused by every test
//! and every later run while valid. A static cannot clean up at process exit, so that directory
//! stays until deleted by hand (it holds game text, like a killed run's leftovers).
//!
//! # Staleness
//!
//! `versions.txt` records the SHA-256 of the four Python tool files and the objdump version.
//! A reference is accepted only when those four hashes equal the hashes of the tool files in the
//! current tree (`tools/` next to this crate) and objdump is [`OBJDUMP_VERSION`]. A hash needs
//! no git; the recorded git revision is informational. Hashes are of the raw bytes, so a
//! checkout that rewrites line endings gives a stale verdict (the gated runs are Linux).

#![allow(dead_code)]


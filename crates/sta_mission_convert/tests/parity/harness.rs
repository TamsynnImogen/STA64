use sha2::{Digest, Sha256};

/// Directory holding a reference written by `tools/convert_reference.py` (read only).
pub const REFERENCE_VAR: &str = "STA64_TEST_LUA_REFERENCE";
/// Armada II install root (read only), as `tests/install.rs` names it.
pub const A2_VAR: &str = "STA64_TEST_A2_STOCK_INSTALL";
/// Armada I install root (read only), as `tests/install.rs` names it.
pub const A1_VAR: &str = "STA64_TEST_A1_INSTALL";
/// The objdump version the Python reference must have been produced with.
pub const OBJDUMP_VERSION: &str = "2.47";
/// The tool files whose hashes `versions.txt` records (`TOOLS` in `convert_reference.py`).
pub const TOOL_FILES: [&str; 4] = [
    "dsl_to_lua.py",
    "drl_to_lua.py",
    "a1_to_lua.py",
    "convert_install_missions.py",
];

/// Which game an install of the reference belongs to (`kind:` in `versions.txt`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Armada1,
    Armada2,
}

/// A reference that is unusable (stale, mismatched, malformed) or could not be produced.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Refusal(pub String);

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

fn refuse<T>(msg: impl Into<String>) -> Result<T, Refusal> {
    Err(Refusal(msg.into()))
}

/// The `tools/` directory of this checkout.
pub fn repo_tools_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tools")
}

/// `target/scratch/` of this checkout: where the developer's detail goes (git-ignored).
pub fn scratch_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/scratch")
}

fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// The `key: value` lines of `versions.txt`.
fn parse_versions(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .filter_map(|l| l.split_once(": "))
        .map(|(k, v)| (k.to_string(), v.trim().to_string()))
        .collect()
}

/// Accept or refuse the recorded versions against `tools_dir` and `objdump_version`.
fn check_versions(
    v: &BTreeMap<String, String>,
    tools_dir: &Path,
    objdump_version: &str,
) -> Result<Kind, Refusal> {
    let kind = match v.get("kind").map(String::as_str) {
        Some("armada1") => Kind::Armada1,
        Some("armada2") => Kind::Armada2,
        _ => return refuse("versions.txt: no usable `kind:` line"),
    };
    match v.get("objdump") {
        Some(o) if o.split_whitespace().last() == Some(objdump_version) => {}
        Some(_) => {
            return refuse(format!(
                "reference refused: it was listed with another objdump than {objdump_version}"
            ))
        }
        None => return refuse("versions.txt: no `objdump:` line"),
    }
    for t in TOOL_FILES {
        let Some(recorded) = v.get(&format!("sha256 tools/{t}")) else {
            return refuse(format!("versions.txt: no hash line for tools/{t}"));
        };
        let current = match fs::read(tools_dir.join(t)) {
            Ok(b) => sha256_hex(&b),
            Err(e) => return refuse(format!("cannot read the current tools/{t}: {e}")),
        };
        if *recorded != current {
            return refuse(format!(
                "reference is stale: tools/{t} differs from the tool revision that wrote it; \
                 write the reference again with tools/convert_reference.py"
            ));
        }
    }
    Ok(kind)
}

/// One install's part of a reference.
#[derive(Debug)]
pub struct RefInstall {
    pub kind: Kind,
    dir: PathBuf,
    versions: BTreeMap<String, String>,
    files: Vec<String>,
}

fn walk_lua(base: &Path, rel: &str, out: &mut Vec<String>) {
    let Ok(rd) = fs::read_dir(base.join(rel)) else {
        return;
    };
    for e in rd.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        let child = if rel.is_empty() {
            name
        } else {
            format!("{rel}/{name}")
        };
        if e.path().is_dir() {
            walk_lua(base, &child, out);
        } else if child.ends_with(".lua") {
            out.push(child);
        }
    }
}

/// `(header, rest)`: the first line with its newline, and the rest. A file without a newline is
/// all header.
fn split_header(bytes: &[u8]) -> (&[u8], &[u8]) {
    match bytes.iter().position(|&b| b == b'\n') {
        Some(i) => bytes.split_at(i + 1),
        None => (bytes, &[]),
    }
}

/// The shape of the header line (line 1) of a converted file, from what the Python tools emit:
///
/// ```text
/// -- <mission>: converted by <tool> (<label>)<tail>\n          missions (dsl_to_lua.py, a1_to_lua.py)
/// -- <mission>: rule scaffold generated by <tool> (<label>).\n  scaffolds (drl_to_lua.py)
/// ```
///
/// where `<tool>` is `tools/<x>_to_lua.py`, `<label>` is `LUA-nn` and `<tail>` is ` from <file>`
/// (plus ` and <file>`) and a final dot, or just the dot. The Rust port names its own tool, so
/// the `<tool> (<label>` part is free (a token without whitespace, a space, `(`, text up to the
/// first `)`); everything else is compared byte for byte, the terminator is `\n` alone and there
/// is no byte order mark.
struct Header<'a> {
    /// Up to and including the space after "converted by" / "generated by".
    prefix: &'a [u8],
    /// From the first `)` after the prefix, including the `\n`.
    tail: &'a [u8],
}

fn find(hay: &[u8], needle: &[u8]) -> Option<usize> {
    hay.windows(needle.len()).position(|w| w == needle)
}

fn parse_header(line: &[u8]) -> Option<Header<'_>> {
    if !line.starts_with(b"-- ") || !line.ends_with(b"\n") || line.ends_with(b"\r\n") {
        return None;
    }
    let (at, len) = [&b": converted by "[..], &b": rule scaffold generated by "[..]]
        .iter()
        .find_map(|c| find(line, c).map(|i| (i, c.len())))?;
    let prefix_end = at + len;
    let close = prefix_end + line[prefix_end..].iter().position(|&b| b == b')')?;
    let tool = &line[prefix_end..close];
    // `<tool> (<label>`: a token, a space, an opening parenthesis, no newline.
    let sp = tool.iter().position(|&b| b == b' ')?;
    if sp == 0 || tool[sp + 1..].first() != Some(&b'(') || tool.contains(&b'\n') {
        return None;
    }
    Some(Header {
        prefix: &line[..prefix_end],
        tail: &line[close..],
    })
}

/// Whether the Rust header has the reference header's shape and the same fixed parts.
fn header_matches(reference: &Header<'_>, rust: &[u8]) -> bool {
    parse_header(rust).is_some_and(|h| h.prefix == reference.prefix && h.tail == reference.tail)
}

/// A header line of the shape the Rust port must emit for the file whose reference header is
/// `reference_header`: the same mission name and tail, the port's own tool token. For tests of
/// the harness and for lifter rows that want a header to put in front of a body.
pub fn ported_header(reference_header: &[u8]) -> Option<Vec<u8>> {
    let h = parse_header(reference_header)?;
    let mut v = h.prefix.to_vec();
    v.extend_from_slice(b"sta_mission_convert (LUA-15");
    v.extend_from_slice(h.tail);
    Some(v)
}

/// The outcome of comparing one file. `Debug` shows the index and line only, never file text.
#[derive(Clone, PartialEq, Eq)]
pub enum Verdict {
    Equal,
    /// First difference at this 1-based line of the file (line 1 is the header: see [`Header`]).
    /// `detail` holds the two differing lines, install-derived game text: for the developer's
    /// scratch file only, never printed.
    Differs {
        index: usize,
        line: usize,
        detail: String,
    },
    /// The reference has no such file.
    NotInReference,
}

impl fmt::Debug for Verdict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Verdict::Equal => f.write_str("Equal"),
            Verdict::Differs { index, line, .. } => {
                write!(f, "Differs {{ index: {index}, line: {line} }}")
            }
            Verdict::NotInReference => f.write_str("NotInReference"),
        }
    }
}

fn lossy_line(bytes: &[u8], line: usize) -> String {
    bytes
        .split(|&b| b == b'\n')
        .nth(line - 1)
        .map_or("(no such line)".to_string(), |l| {
            String::from_utf8_lossy(l).into_owned()
        })
}

/// Compare two outputs: the header by shape (see [`Header`]), the rest byte for byte; `index`
/// goes into the verdict.
fn compare_bytes(index: usize, reference: &[u8], rust: &[u8]) -> Verdict {
    let (rh, r) = split_header(reference);
    let (th, t) = split_header(rust);
    let differs = |line: usize| Verdict::Differs {
        index,
        line,
        detail: format!(
            "reference: {}\nrust:      {}",
            lossy_line(reference, line),
            lossy_line(rust, line)
        ),
    };
    if !parse_header(rh).is_some_and(|h| header_matches(&h, th)) {
        return differs(1);
    }
    if r == t {
        return Verdict::Equal;
    }
    let common = r.iter().zip(t).take_while(|(a, b)| a == b).count();
    // The header is line 1; the body starts on line 2.
    differs(2 + r[..common].iter().filter(|&&b| b == b'\n').count())
}

/// The result of comparing an output with an install's reference. `Debug` shows counts and
/// indices only, never file names or text.
#[derive(Default)]
pub struct Report {
    pub equal: usize,
    /// `(index, line, detail)` of every file that differs (`detail` is game text: never print it).
    pub differing: Vec<(usize, usize, String)>,
    /// Indices of reference files the output lacks.
    pub missing: Vec<usize>,
    /// Output files the reference lacks (relative paths: for the scratch file only).
    pub extra: Vec<String>,
    /// Reference file names by index, for the scratch file only.
    names: Vec<String>,
}

impl fmt::Debug for Report {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "Report {{ equal: {}, differing (index, line): {:?}, missing: {:?}, extra: {} }}",
            self.equal,
            self.differing
                .iter()
                .map(|(i, l, _)| (*i, *l))
                .collect::<Vec<_>>(),
            self.missing,
            self.extra.len()
        )
    }
}

impl Report {
    pub fn is_ok(&self) -> bool {
        self.differing.is_empty() && self.missing.is_empty() && self.extra.is_empty()
    }

    /// Panic unless equal. The message carries counts, indices and line numbers only; the
    /// detail (names and the differing lines, install-derived) goes to
    /// `target/scratch/parity-<label>.txt`.
    pub fn assert_ok(&self, label: &str) {
        if self.is_ok() {
            return;
        }
        let mut detail = String::new();
        for (i, l, d) in &self.differing {
            detail += &format!("index {i} ({}) line {l}\n{d}\n\n", self.names[*i]);
        }
        for i in &self.missing {
            detail += &format!("index {i} ({}) missing from the output\n", self.names[*i]);
        }
        for e in &self.extra {
            detail += &format!("extra in the output: {e}\n");
        }
        let safe: String = label
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '-' {
                    c
                } else {
                    '_'
                }
            })
            .collect();
        let path = scratch_dir().join(format!("parity-{safe}.txt"));
        let wrote = fs::create_dir_all(scratch_dir()).is_ok() && fs::write(&path, detail).is_ok();
        panic!(
            "parity {label}: {} equal; differing (index, line): {:?}; missing indices: {:?}; \
             extra files: {}; detail {}",
            self.equal,
            self.differing
                .iter()
                .map(|(i, l, _)| (*i, *l))
                .collect::<Vec<_>>(),
            self.missing,
            self.extra.len(),
            if wrote {
                "in target/scratch"
            } else {
                "could not be written"
            },
        );
    }
}

impl RefInstall {
    /// Relative paths of the reference's `.lua` files, sorted; the position is the index.
    pub fn files(&self) -> &[String] {
        &self.files
    }

    pub fn index_of(&self, rel: &str) -> Option<usize> {
        self.files.binary_search_by(|f| f.as_str().cmp(rel)).ok()
    }

    /// The reference file's bytes.
    pub fn read(&self, rel: &str) -> Option<Vec<u8>> {
        self.index_of(rel)?;
        fs::read(self.dir.join(rel)).ok()
    }

    /// `PYTHONHASHSEED` the reference ran with.
    pub fn hashseed(&self) -> Option<&str> {
        self.versions.get("PYTHONHASHSEED").map(String::as_str)
    }

    /// Whether the reference was written with `--include-unmapped` (Armada I: extra files).
    pub fn include_unmapped(&self) -> bool {
        self.versions
            .get("flags")
            .is_some_and(|f| f.contains("include-unmapped=True"))
    }

    /// An objdump listing written with `--objdump-listings`, by file name (`<dll, lower
    /// case>.txt`). `None` when the reference has none.
    pub fn listing(&self, name: &str) -> Option<Vec<u8>> {
        if name.contains(['/', '\\']) {
            return None;
        }
        fs::read(self.dir.join("listings").join(name)).ok()
    }

    pub fn has_listings(&self) -> bool {
        self.dir.join("listings").is_dir()
    }

    /// Compare the Rust output of one file with the reference file `rel`, ignoring only the
    /// first line of each.
    pub fn compare(&self, rel: &str, rust: &[u8]) -> Verdict {
        let Some(index) = self.index_of(rel) else {
            return Verdict::NotInReference;
        };
        let reference = fs::read(self.dir.join(rel))
            .unwrap_or_else(|e| panic!("reference file with index {index} unreadable: {e}"));
        compare_bytes(index, &reference, rust)
    }

    /// Compare a whole output (relative path to bytes) with the reference.
    pub fn compare_all(&self, produced: &BTreeMap<String, Vec<u8>>) -> Report {
        self.compare_subset(produced, |_| true)
    }

    /// Compare only the part of the run `keep` selects (by relative path: a prefix such as
    /// `drl/`, a list of missions, ...). Reference files outside it are not counted as missing,
    /// output files outside it are not counted as extra; indices stay those of the whole run.
    pub fn compare_subset(
        &self,
        produced: &BTreeMap<String, Vec<u8>>,
        keep: impl Fn(&str) -> bool,
    ) -> Report {
        let mut rep = Report {
            names: self.files.clone(),
            ..Report::default()
        };
        for (i, f) in self.files.iter().enumerate().filter(|(_, f)| keep(f)) {
            match produced.get(f) {
                None => rep.missing.push(i),
                Some(bytes) => match self.compare(f, bytes) {
                    Verdict::Equal => rep.equal += 1,
                    Verdict::Differs {
                        index,
                        line,
                        detail,
                    } => rep.differing.push((index, line, detail)),
                    Verdict::NotInReference => unreachable!("listed file"),
                },
            }
        }
        rep.extra = produced
            .keys()
            .filter(|k| keep(k) && self.index_of(k).is_none())
            .cloned()
            .collect();
        rep
    }
}

/// A reference: one or more installs' outputs, validated.
#[derive(Debug)]
pub struct Reference {
    installs: Vec<RefInstall>,
}

impl Reference {
    pub fn installs(&self) -> &[RefInstall] {
        &self.installs
    }

    /// The first install of this kind.
    pub fn install(&self, kind: Kind) -> Option<&RefInstall> {
        self.installs.iter().find(|i| i.kind == kind)
    }

    /// Load and validate the reference in `root`: either an install folder itself (it holds
    /// `versions.txt`) or a folder of install folders, as `convert_reference.py --out` writes.
    /// Read only. `tools_dir` and `objdump_version` say what counts as current.
    pub fn load(
        root: &Path,
        tools_dir: &Path,
        objdump_version: &str,
    ) -> Result<Reference, Refusal> {
        let mut dirs = Vec::new();
        if root.join("versions.txt").is_file() {
            dirs.push(root.to_path_buf());
        } else {
            let rd = fs::read_dir(root)
                .map_err(|e| Refusal(format!("reference folder unreadable: {e}")))?;
            for e in rd.flatten() {
                if e.path().join("versions.txt").is_file() {
                    dirs.push(e.path());
                }
            }
            dirs.sort();
        }
        if dirs.is_empty() {
            return refuse("reference folder holds no install (no versions.txt)");
        }
        let mut installs = Vec::new();
        for dir in dirs {
            let text = fs::read_to_string(dir.join("versions.txt"))
                .map_err(|e| Refusal(format!("versions.txt unreadable: {e}")))?;
            let versions = parse_versions(&text);
            let kind = check_versions(&versions, tools_dir, objdump_version)?;
            let mut files = Vec::new();
            walk_lua(&dir, "", &mut files);
            files.sort();
            // Layout: every file is a mission or a scaffold, and its header line names the tool.
            for f in &files {
                if !(f.starts_with("missions/") || f.starts_with("drl/")) {
                    return refuse("reference holds a .lua file outside missions/ and drl/");
                }
                let bytes = fs::read(dir.join(f))
                    .map_err(|e| Refusal(format!("reference file unreadable: {e}")))?;
                let (head, _) = split_header(&bytes);
                if parse_header(head).is_none() {
                    return refuse("a reference file's first line has not the converter header shape");
                }
            }
            installs.push(RefInstall {
                kind,
                dir,
                versions,
                files,
            });
        }
        Ok(Reference { installs })
    }
}

/// A fresh directory under the system temp dir, removed on drop.
#[derive(Debug)]
pub struct TempDir(PathBuf);

impl TempDir {
    pub fn new(tag: &str) -> TempDir {
        static N: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.subsec_nanos());
        let p = std::env::temp_dir().join(format!(
            "sta64-parity-{tag}-{}-{}-{nanos}",
            std::process::id(),
            N.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
        ));
        fs::create_dir_all(&p).expect("temp dir");
        TempDir(p)
    }

    pub fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn inside(path: &Path, root: &Path) -> bool {
    match (path.canonicalize(), root.canonicalize()) {
        (Ok(p), Ok(r)) => p.starts_with(r),
        _ => false,
    }
}

/// First line of `<cmd> --version`, or `None` when the command does not run.
fn tool_version(cmd: &str) -> Option<String> {
    let out = Command::new(cmd)
        .arg("--version")
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    out.status
        .success()
        .then(|| String::from_utf8_lossy(&out.stdout).lines().next().unwrap_or("").to_string())
}

/// A variable naming a directory: unset or empty is `None`, set to anything else that is not a
/// directory is a refusal (a typo must not turn a stored-reference run into a skip).
fn env_dir(name: &str) -> Result<Option<PathBuf>, Refusal> {
    match std::env::var_os(name) {
        None => Ok(None),
        Some(v) if v.is_empty() => Ok(None),
        Some(v) => {
            let p = PathBuf::from(v);
            if p.is_dir() {
                Ok(Some(p))
            } else {
                refuse(format!("{name} is set but is not a directory"))
            }
        }
    }
}

/// A cheap fingerprint of an install for the reference key: the relative path, size and
/// modification time (seconds) of every `.dsl`, `.drl`, `.exe`, `.map` and `.bzn` file down to
/// three levels. A heuristic: it detects a changed, replaced or patched install, not a rewrite
/// that keeps size and time.
fn install_fingerprint(h: &mut Sha256, root: &Path) {
    fn walk(dir: &Path, rel: &str, depth: u32, h: &mut Sha256) {
        let Ok(rd) = fs::read_dir(dir) else {
            return;
        };
        let mut entries: Vec<_> = rd.flatten().collect();
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let name = e.file_name().to_string_lossy().to_lowercase();
            let Ok(md) = e.metadata() else {
                continue;
            };
            if md.is_dir() {
                if depth > 0 {
                    walk(&e.path(), &format!("{rel}/{name}"), depth - 1, h);
                }
            } else if [".dsl", ".drl", ".exe", ".map", ".bzn"]
                .iter()
                .any(|x| name.ends_with(x))
            {
                let secs = md
                    .modified()
                    .ok()
                    .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
                    .map_or(0, |d| d.as_secs());
                h.update(format!("{rel}/{name} {} {secs}\n", md.len()));
            }
        }
    }
    walk(root, "", 3, h);
}

/// The deterministic directory a self-generated reference lives in: under the system temp dir,
/// keyed by the four tool hashes, the install paths and a fingerprint of their files, the
/// objdump version and the harness layout.
fn generated_dir(tools: &Path, installs: &[PathBuf]) -> Result<PathBuf, Refusal> {
    let mut h = Sha256::new();
    for t in TOOL_FILES {
        let b = fs::read(tools.join(t))
            .map_err(|e| Refusal(format!("cannot read the current tools/{t}: {e}")))?;
        h.update(sha256_hex(&b));
    }
    for i in installs {
        h.update(i.canonicalize().unwrap_or_else(|_| i.clone()).to_string_lossy().as_bytes());
        h.update([0]);
        install_fingerprint(&mut h, i);
    }
    h.update(OBJDUMP_VERSION);
    h.update("layout-2");
    let key: String = h.finalize().iter().take(8).map(|b| format!("{b:02x}")).collect();
    Ok(std::env::temp_dir().join(format!("sta64-parity-ref-{key}")))
}

/// Create one directory (its parent exists) readable by the owner only: mode 0700 on Unix. On
/// Windows the directory inherits the access of the user's temp folder (the user profile).
pub fn make_private_dir(p: &Path) -> std::io::Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        fs::DirBuilder::new().mode(0o700).create(p)
    }
    #[cfg(not(unix))]
    {
        fs::create_dir(p)
    }
}

/// A path next to `dir` that no other process or call uses.
fn unique_sibling(dir: &Path, what: &str) -> PathBuf {
    static N: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.subsec_nanos());
    let name = dir.file_name().map_or(String::new(), |n| n.to_string_lossy().into_owned());
    dir.with_file_name(format!(
        "{name}.{what}-{}-{}-{nanos}",
        std::process::id(),
        N.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ))
}

/// What a generated-reference directory is.
#[derive(Debug, PartialEq, Eq)]
pub enum DirState {
    Missing,
    /// Ours and private: may be reused if its content validates.
    Usable,
    /// Ours but reachable by group or others (Unix): to be replaced.
    WrongMode,
}

/// Classify `dir`. A symlink, a non-directory or (Unix, `my_uid` known) a directory of another
/// user is a refusal: nothing is reused, replaced or deleted there.
pub fn dir_state(dir: &Path, my_uid: Option<u32>) -> Result<DirState, Refusal> {
    let md = match fs::symlink_metadata(dir) {
        Ok(md) => md,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(DirState::Missing),
        Err(e) => return refuse(format!("cannot inspect the generated reference directory: {e}")),
    };
    if md.file_type().is_symlink() || !md.is_dir() {
        return refuse("the generated reference path is a symlink or not a directory: refused");
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        if my_uid.is_some_and(|u| u != md.uid()) {
            return refuse("the generated reference directory belongs to another user: refused");
        }
        if md.mode() & 0o077 != 0 {
            return Ok(DirState::WrongMode);
        }
    }
    let _ = my_uid;
    Ok(DirState::Usable)
}

/// The current user's id (Unix): the owner of a private directory just made under `parent`.
fn current_uid(parent: &Path) -> Option<u32> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        let probe = unique_sibling(&parent.join("sta64-parity-probe"), "uid");
        make_private_dir(&probe).ok()?;
        let uid = fs::symlink_metadata(&probe).ok().map(|m| m.uid());
        let _ = fs::remove_dir(&probe);
        uid
    }
    #[cfg(not(unix))]
    {
        let _ = parent;
        None
    }
}

/// Run `convert_reference.py` for `installs` into a new private directory next to `dir` and
/// return it.
fn generate(tools: &Path, installs: &[PathBuf], dir: &Path) -> Result<PathBuf, Refusal> {
    let work = unique_sibling(dir, "work");
    make_private_dir(&work)
        .map_err(|e| Refusal(format!("cannot create the reference directory: {e}")))?;
    let mut cmd = Command::new("python3");
    // `-I` (isolated): no PYTHONPATH, no user site, no cwd on the path; the script puts its own
    // directory on `sys.path` and pins the environment of its children itself.
    cmd.arg("-I")
        .arg(tools.join("convert_reference.py"))
        .arg("--out")
        .arg(&work)
        .arg("--objdump-listings");
    for i in installs {
        cmd.arg("--install").arg(i);
    }
    let status = cmd
        .current_dir(&work)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    match status {
        Ok(s) if s.success() => Ok(work),
        Ok(s) => {
            let _ = fs::remove_dir_all(&work);
            refuse(format!("convert_reference.py failed: {s}"))
        }
        Err(e) => {
            let _ = fs::remove_dir_all(&work);
            refuse(format!("could not run convert_reference.py: {e}"))
        }
    }
}

/// Whether `dir` is ours, private and a valid current reference.
fn is_current(dir: &Path, tools: &Path, uid: Option<u32>) -> bool {
    matches!(dir_state(dir, uid), Ok(DirState::Usable))
        && Reference::load(dir, tools, OBJDUMP_VERSION).is_ok()
}

/// Put the finished `work` directory at `dir` without ever deleting a directory that validates as
/// current (the race of two test binaries replacing the same stale one): the generated directory
/// is built under its own unique name and renamed into place (atomic; it fails while a non-empty
/// directory is there); a stale occupant is renamed aside, and if what was moved aside turns out
/// to be current (another process replaced the stale one meanwhile) it is put back and `work` is
/// dropped. A symlink or a directory of another user at `dir` is a hard failure.
fn place(work: &Path, dir: &Path, tools: &Path, uid: Option<u32>) -> Result<(), Refusal> {
    for _ in 0..3 {
        if fs::rename(work, dir).is_ok() {
            return Ok(());
        }
        if is_current(dir, tools, uid) {
            let _ = fs::remove_dir_all(work);
            return Ok(());
        }
        dir_state(dir, uid)?;
        let aside = unique_sibling(dir, "old");
        if fs::rename(dir, &aside).is_err() {
            continue;
        }
        if is_current(&aside, tools, uid) {
            if fs::rename(&aside, dir).is_err() {
                let _ = fs::remove_dir_all(&aside);
            }
            let _ = fs::remove_dir_all(work);
            return Ok(());
        }
        let _ = fs::remove_dir_all(&aside);
    }
    let _ = fs::remove_dir_all(work);
    refuse("cannot move the generated reference into place")
}

fn obtain_uncached() -> Result<Option<Arc<Reference>>, Refusal> {
    let tools = repo_tools_dir();
    if let Some(dir) = env_dir(REFERENCE_VAR)? {
        // A stored reference: any mismatch is a hard failure.
        return Ok(Some(Arc::new(Reference::load(&dir, &tools, OBJDUMP_VERSION)?)));
    }
    let mut installs = Vec::new();
    for v in [A2_VAR, A1_VAR] {
        installs.extend(env_dir(v)?);
    }
    if installs.is_empty() {
        eprintln!(
            "parity skipped: neither {REFERENCE_VAR} nor an install ({A2_VAR}, {A1_VAR}) is set"
        );
        return Ok(None);
    }
    if tool_version("python3").is_none() {
        eprintln!("parity skipped: {REFERENCE_VAR} is not set and python3 is not available");
        return Ok(None);
    }
    match tool_version("objdump") {
        Some(v) if v.split_whitespace().last() == Some(OBJDUMP_VERSION) => {}
        _ => {
            eprintln!(
                "parity skipped: {REFERENCE_VAR} is not set and objdump {OBJDUMP_VERSION} is not available"
            );
            return Ok(None);
        }
    }
    // Never create anything in the repository or an install, even by a misplaced TMPDIR.
    let tmp = std::env::temp_dir();
    if installs.iter().any(|i| inside(&tmp, i)) || inside(&tmp, &tools) {
        return refuse("the system temp directory lies inside an install or the repository: refused");
    }
    let uid = current_uid(&tmp);
    let dir = generated_dir(&tools, &installs)?;
    if !is_current(&dir, &tools, uid) {
        // Refuses a symlink or another user's directory before anything is generated.
        dir_state(&dir, uid)?;
        let work = generate(&tools, &installs, &dir)?;
        place(&work, &dir, &tools, uid)?;
    }
    Ok(Some(Arc::new(Reference::load(&dir, &tools, OBJDUMP_VERSION)?)))
}

/// Where the reference comes from, in this order:
///
/// 1. the folder named by [`REFERENCE_VAR`] (read only; set but not a directory, stale or
///    malformed is `Err`);
/// 2. else, when `python3` and objdump [`OBJDUMP_VERSION`] run and [`A2_VAR`] / [`A1_VAR`] name
///    installs, `tools/convert_reference.py` is run (about 40 s) into
///    `<system temp>/sta64-parity-ref-<key>`. The workspace has no user cache helper outside the
///    `sta64` crate, so the temp directory is used, with these safeguards: the directory and its
///    build sibling are created mode 0700 (Unix; on Windows the user's temp folder in the user
///    profile protects them), a directory of another user, a symlink, or one not owned by us is
///    refused, one of ours with group or other access is replaced. `<key>` hashes the tool
///    hashes, the install paths, a fingerprint of the installs' `.dsl`, `.drl`, `.exe`, `.map`
///    and `.bzn` files (path, size, modification time: a heuristic that detects a changed or
///    patched install) and the objdump version. The directory is reused while it loads as valid
///    and **never removed** (a static cannot clean up at process exit): delete it by hand when
///    done. It holds install-derived text, as do the `.work-*` and `.old-*` leftovers of a killed
///    run. Two processes finding the same stale directory cannot delete each other's fresh one
///    (see `place`: unique build names, atomic rename, a moved-aside directory that validates is
///    put back);
/// 3. else `Ok(None)` and the reason goes to stderr (skip): nothing set, no python3, or another
///    objdump version (a reference written by the harness itself with another objdump would be
///    refused anyway).
///
/// The result is computed once per test binary (a `OnceLock`); every test binary that includes
/// this module through `#[path]` computes its own, but finds the directory of the first.
pub fn obtain() -> Result<Option<Arc<Reference>>, Refusal> {
    static CACHE: OnceLock<Result<Option<Arc<Reference>>, Refusal>> = OnceLock::new();
    CACHE.get_or_init(obtain_uncached).clone()
}

/// [`obtain`] for a test: a refused reference panics with the reason, no reference skips.
pub fn obtain_or_skip() -> Option<Arc<Reference>> {
    match obtain() {
        Ok(r) => r,
        Err(e) => panic!("{e}"),
    }
}

/// Build a synthetic reference for the harness's own tests: invented content, not from any game.
pub mod synthetic {
    use super::*;

    /// Write four invented tool files into `tools`; the hashes follow from them.
    pub fn write_tools(tools: &Path, tag: &str) {
        fs::create_dir_all(tools).unwrap();
        for t in TOOL_FILES {
            fs::write(tools.join(t), format!("invented tool {t} {tag}\n")).unwrap();
        }
    }

    /// Write an install folder `dir` in the reference layout with `files` (relative path ->
    /// content) and a `versions.txt` for the tools in `tools`.
    pub fn write_install(
        dir: &Path,
        kind: &str,
        tools: &Path,
        objdump: &str,
        files: &[(&str, &str)],
    ) {
        fs::create_dir_all(dir).unwrap();
        let mut v = format!("kind: {kind}\ntools git revision: (unknown)\n");
        for t in TOOL_FILES {
            let h = sha256_hex(&fs::read(tools.join(t)).unwrap());
            v += &format!("sha256 tools/{t}: {h}\n");
        }
        v += &format!("objdump: GNU objdump (GNU Binutils) {objdump}\n");
        v += "PYTHONHASHSEED: 0\nflags: include-unmapped=False objdump-listings=False\n";
        fs::write(dir.join("versions.txt"), v).unwrap();
        for (rel, content) in files {
            let p = dir.join(rel);
            fs::create_dir_all(p.parent().unwrap()).unwrap();
            fs::write(p, content).unwrap();
        }
    }
}

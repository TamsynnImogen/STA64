//! Parity of the Rust converter with the Python reference (LUA-15f, step S8).
//!
//! The reference is what `tools/convert_reference.py` wrote for an install. The comparison is
//! byte for byte except the first line of each file (it names the tool); see `parity/harness.rs`
//! for the API the lifter rows (LUA-15g, 15h, 15e) add their cases through, for what is
//! compared, and for how a stale reference is detected (SHA-256 of the four Python tool files and
//! the objdump version, both recorded in the reference's `versions.txt`).
//!
//! # Running
//!
//! The harness only reads installs and the reference, and writes only to a temp directory
//! (removed afterwards) and to `target/scratch/`. Without any variable the gated test skips with
//! a message on stderr; the synthetic self-tests always run.
//!
//! ```text
//! # Reference run by the harness itself (needs python3 and objdump 2.47; about 40 s):
//! /path/to/build2 test -p sta_mission_convert --test parity \
//!     --config 'env.STA64_TEST_A2_STOCK_INSTALL="/path/to/Armada II"' \
//!     --config 'env.STA64_TEST_A1_INSTALL="/path/to/Armada"'
//!
//! # Reference written once, outside the repository and the installs, and reused:
//! python3 tools/convert_reference.py --out /tmp/ref --install "/path/to/Armada II" \
//!     --install "/path/to/Armada" --objdump-listings
//! /path/to/build2 test -p sta_mission_convert --test parity \
//!     --config 'env.STA64_TEST_LUA_REFERENCE="/tmp/ref"'
//! ```
//!
//! The generated reference lives in `<system temp>/sta64-parity-ref-<key>` (key: the tool hashes,
//! the install paths, the objdump version), is reused by every test and every later run while it
//! is valid, and is not removed (a static cannot clean up at exit): delete it by hand. It, a
//! killed run's `.tmp<pid>` leftover and the failure detail file `target/scratch/parity-<label>.txt`
//! all hold game text: never commit, attach or paste them. A generated reference needs objdump
//! 2.47; with another version the test skips with a message (a stored reference with another
//! version is refused).
//!
//! (`build2` is the worker wrapper of the coordinated session; elsewhere use
//! `tools/agent-cargo test ...` with the same arguments.) A reference made from an older tool
//! revision is refused with a message: write it again.

#[path = "parity/harness.rs"]
mod harness;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use harness::synthetic::{write_install, write_tools};
use harness::{Kind, Reference, TempDir, Verdict, OBJDUMP_VERSION};

const BODY: &str = "-- invented: converted by tools/dsl_to_lua.py (LUA-11) from x.dsl.\nline two\nline three\nline four\n";
const RUST_HEADER: &str = "-- invented: converted by sta_mission_convert (LUA-15h) from x.dsl.\n";
const SCAFFOLD: &str =
    "-- invented: rule scaffold generated by tools/drl_to_lua.py (LUA-07).\nx\n";

fn synthetic() -> (TempDir, PathBuf, PathBuf) {
    let t = TempDir::new("self");
    let tools = t.path().join("tools");
    write_tools(&tools, "a");
    let dir = t.path().join("ref");
    write_install(
        &dir.join("armada-x"),
        "armada2",
        &tools,
        OBJDUMP_VERSION,
        &[
            ("missions/one.lua", BODY),
            ("missions/two.lua", BODY),
            ("drl/missions/one.lua", SCAFFOLD),
        ],
    );
    (t, tools, dir)
}

fn load(dir: &Path, tools: &Path) -> Result<Reference, harness::Refusal> {
    Reference::load(dir, tools, OBJDUMP_VERSION)
}

fn good_output() -> BTreeMap<String, Vec<u8>> {
    [
        ("missions/one.lua", BODY),
        ("missions/two.lua", BODY),
        ("drl/missions/one.lua", "-- invented: rule scaffold generated by sta_mission_convert (LUA-15g).\nx\n"),
    ]
    .iter()
    .map(|(k, v)| (k.to_string(), v.as_bytes().to_vec()))
    .collect()
}

#[test]
fn self_equal_and_header_only_difference() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    assert_eq!(
        i.files(),
        ["drl/missions/one.lua", "missions/one.lua", "missions/two.lua"]
    );
    let mut out = good_output();
    // Only the first line differs (the scaffold's does): equal.
    let rep = i.compare_all(&out);
    assert!(rep.is_ok(), "{rep:?}");
    assert_eq!(rep.equal, 3);
    // A different header on a mission file too.
    out.insert(
        "missions/one.lua".into(),
        BODY.replacen("LUA-11", "LUA-99", 1).into_bytes(),
    );
    assert_eq!(
        i.compare("missions/one.lua", &out["missions/one.lua"]),
        Verdict::Equal
    );
    // An output without any newline is all header, and not a header at all.
    assert!(matches!(
        i.compare("missions/one.lua", b"x"),
        Verdict::Differs { line: 1, .. }
    ));
}

#[test]
fn self_header_only_the_tool_token_is_free() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    let body = "line two\nline three\nline four\n";
    let with = |h: &str| format!("{h}{body}").into_bytes();
    let check = |h: &str| i.compare("missions/one.lua", &with(h));
    // The tool token and label differ: passes.
    assert_eq!(check(RUST_HEADER), Verdict::Equal);
    assert_eq!(check("-- invented: converted by x (y) from x.dsl.\n"), Verdict::Equal);
    // Wrong mission name, wrong source part, wrong tail, wrong connector.
    for bad in [
        "-- other: converted by sta_mission_convert (LUA-15h) from x.dsl.\n",
        "-- invented: converted by sta_mission_convert (LUA-15h) from y.dsl.\n",
        "-- invented: converted by sta_mission_convert (LUA-15h) from x.dsl\n",
        "-- invented: converted by sta_mission_convert (LUA-15h) from x.dsl. \n",
        "-- invented: generated by sta_mission_convert (LUA-15h) from x.dsl.\n",
        // No tool word, no parenthesis, a token with a space, empty header, no header.
        "-- invented: converted by from x.dsl.\n",
        "-- invented: converted by sta_mission_convert from x.dsl.)\n",
        "-- invented: converted by a b (LUA-15h) from x.dsl.\n",
        "\n",
        "",
    ] {
        assert!(matches!(check(bad), Verdict::Differs { line: 1, .. }), "{bad:?}");
    }
    // A byte order mark and a CRLF terminator.
    let bom = format!("\u{feff}{RUST_HEADER}");
    assert!(matches!(check(&bom), Verdict::Differs { line: 1, .. }));
    let crlf = RUST_HEADER.replace(".\n", ".\r\n");
    assert!(matches!(check(&crlf), Verdict::Differs { line: 1, .. }));
    // The scaffold header has its own connector.
    assert_eq!(
        i.compare("drl/missions/one.lua", b"-- invented: rule scaffold generated by z (LUA-1).\nx\n"),
        Verdict::Equal
    );
    assert!(matches!(
        i.compare("drl/missions/one.lua", b"-- invented: converted by z (LUA-1).\nx\n"),
        Verdict::Differs { line: 1, .. }
    ));
    // A header the body difference sits behind is still reported at its own line.
    let mut longer = with(RUST_HEADER);
    longer.push(b'!');
    assert!(matches!(
        i.compare("missions/one.lua", &longer),
        Verdict::Differs { line: 5, .. }
    ));
}

#[test]
fn self_debug_output_carries_no_file_text() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    let v = i.compare("missions/one.lua", BODY.replace("line three", "line 3").as_bytes());
    assert!(matches!(v, Verdict::Differs { index: 1, line: 3, .. }));
    let text = format!("{v:?} {:?}", i.compare_all(&BTreeMap::from([("zz.lua".to_string(), BODY.as_bytes().to_vec())])));
    assert!(!text.contains("line three") && !text.contains("line 3") && !text.contains("zz.lua"), "{text}");
    let mut out = good_output();
    out.insert("missions/two.lua".into(), BODY.replace("line three", "line 3").into_bytes());
    let text = format!("{:?}", i.compare_all(&out));
    assert!(!text.contains("line three") && !text.contains("line 3") && !text.contains("two.lua"), "{text}");
}

#[test]
fn self_subset_counts_only_the_selected_files() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    // Scaffolds only: the missions are neither missing nor extra, indices stay global.
    let mut out = BTreeMap::new();
    out.insert("drl/missions/one.lua".to_string(), b"-- invented: rule scaffold generated by z (LUA-1).\nx\n".to_vec());
    out.insert("missions/stray.lua".to_string(), b"x".to_vec());
    let rep = i.compare_subset(&out, |rel| rel.starts_with("drl/"));
    assert!(rep.is_ok(), "{rep:?}");
    assert_eq!(rep.equal, 1);
    // The same output as a whole run is not ok.
    assert!(!i.compare_all(&out).is_ok());
    // A subset with a differing file reports the global index.
    out.insert("missions/two.lua".to_string(), BODY.replace("four", "4").into_bytes());
    let rep = i.compare_subset(&out, |rel| rel == "missions/two.lua");
    assert_eq!(rep.differing.iter().map(|d| (d.0, d.1)).collect::<Vec<_>>(), [(2, 4)]);
    assert!(rep.missing.is_empty() && rep.extra.is_empty());
}

#[test]
fn self_difference_reports_index_and_line() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    let mut out = good_output();
    out.insert(
        "missions/two.lua".into(),
        BODY.replace("line three", "line 3").into_bytes(),
    );
    let rep = i.compare_all(&out);
    assert_eq!(rep.equal, 2);
    assert_eq!(rep.differing.len(), 1);
    assert_eq!((rep.differing[0].0, rep.differing[0].1), (2, 3));
    // The detail is for the scratch file; the panic message names no file and shows no content.
    assert!(rep.differing[0].2.contains("line three"));
    let msg = std::panic::catch_unwind(|| rep.assert_ok("self-test"))
        .unwrap_err()
        .downcast::<String>()
        .unwrap();
    assert!(msg.contains("(2, 3)") && !msg.contains("two.lua") && !msg.contains("line three"));
    // Truncated and extended outputs differ at the first missing or extra line.
    let cut = format!("{RUST_HEADER}line two\n");
    assert!(matches!(
        i.compare("missions/one.lua", cut.as_bytes()),
        Verdict::Differs { line: 3, .. }
    ));
    let more = format!("{BODY}line five\n");
    assert!(matches!(
        i.compare("missions/one.lua", more.as_bytes()),
        Verdict::Differs { line: 5, .. }
    ));
    // Last byte (the final newline of line 4) changed.
    let mut b = BODY.as_bytes().to_vec();
    *b.last_mut().unwrap() = b'!';
    assert!(matches!(
        i.compare("missions/one.lua", &b),
        Verdict::Differs { line: 4, .. }
    ));
}

#[test]
fn self_missing_and_extra_files() {
    let (_t, tools, dir) = synthetic();
    let r = load(&dir, &tools).unwrap();
    let i = r.install(Kind::Armada2).unwrap();
    let mut out = good_output();
    out.remove("missions/one.lua");
    out.insert("missions/three.lua".into(), RUST_HEADER.as_bytes().to_vec());
    let rep = i.compare_all(&out);
    assert_eq!(
        (rep.equal, rep.missing.clone(), rep.extra.len()),
        (2, vec![1], 1)
    );
    assert!(!rep.is_ok());
    assert_eq!(
        i.compare("missions/three.lua", b"x"),
        Verdict::NotInReference
    );
}

#[test]
fn self_stale_and_mismatched_versions_are_refused() {
    let (t, tools, dir) = synthetic();
    assert!(load(&dir, &tools).is_ok());
    // The tool changed after the reference was written: stale.
    fs::write(tools.join("a1_to_lua.py"), "edited\n").unwrap();
    let e = load(&dir, &tools).unwrap_err();
    assert!(e.0.contains("stale") && e.0.contains("a1_to_lua.py"), "{e}");
    // Another objdump.
    let dir2 = t.path().join("ref2");
    write_install(&dir2, "armada1", &tools, "2.46", &[("missions/a.lua", BODY)]);
    assert!(load(&dir2, &tools).unwrap_err().0.contains("objdump"));
    // No hash line, unknown kind, empty folder, stray layout, header naming no tool.
    let dir3 = t.path().join("ref3");
    write_install(&dir3, "armada1", &tools, OBJDUMP_VERSION, &[]);
    let v = fs::read_to_string(dir3.join("versions.txt")).unwrap();
    fs::write(
        dir3.join("versions.txt"),
        v.replace("sha256 tools/drl_to_lua.py", "x"),
    )
    .unwrap();
    assert!(load(&dir3, &tools).is_err());
    let dir4 = t.path().join("ref4");
    write_install(&dir4, "bogus", &tools, OBJDUMP_VERSION, &[]);
    assert!(load(&dir4, &tools).is_err());
    assert!(load(&t.path().join("tools"), &tools).is_err());
    let dir5 = t.path().join("ref5");
    write_install(
        &dir5,
        "armada1",
        &tools,
        OBJDUMP_VERSION,
        &[("other/a.lua", BODY)],
    );
    assert!(load(&dir5, &tools).is_err());
    let dir6 = t.path().join("ref6");
    write_install(
        &dir6,
        "armada1",
        &tools,
        OBJDUMP_VERSION,
        &[("missions/a.lua", "-- no tool\n")],
    );
    assert!(load(&dir6, &tools).is_err());
}


/// Gated: the real reference (from `STA64_TEST_LUA_REFERENCE`, or written by running the Python
/// tool on the installs) has the expected structure, is accepted, round-trips through the
/// comparison and fails on a one-byte change. Content is never asserted or printed.
#[test]
fn gated_reference_structure_and_roundtrip() {
    let Some(r) = harness::obtain_or_skip() else {
        return;
    };
    assert!(!r.installs().is_empty());
    if std::env::var_os(harness::REFERENCE_VAR).is_none() {
        for (var, kind) in [
            (harness::A2_VAR, Kind::Armada2),
            (harness::A1_VAR, Kind::Armada1),
        ] {
            if std::env::var_os(var).is_some_and(|v| Path::new(&v).is_dir()) {
                assert!(r.install(kind).is_some(), "{var} is set: no such install");
            }
        }
    }
    for i in r.installs() {
        let n = i.files().len();
        let missions = i.files().iter().filter(|f| f.starts_with("missions/")).count();
        let drl = i.files().iter().filter(|f| f.starts_with("drl/")).count();
        assert!(missions > 0, "no mission file");
        assert_eq!(missions + drl, n);
        if i.kind == Kind::Armada2 {
            assert!(drl > 0, "no rule scaffold");
        }
        eprintln!(
            "parity reference: {:?}: {n} files ({missions} missions, {drl} scaffolds), listings: {}",
            i.kind,
            i.has_listings()
        );
        // The reference as the Rust output passes.
        let produced: BTreeMap<String, Vec<u8>> = i
            .files()
            .iter()
            .map(|f| (f.clone(), i.read(f).unwrap()))
            .collect();
        i.compare_all(&produced).assert_ok("roundtrip");
        // A header with the port's own tool token passes, a one-byte change in the body fails with its index.
        let first = &i.files()[0];
        let bytes = &produced[first];
        let cut = bytes.iter().position(|&b| b == b'\n').unwrap() + 1;
        let mut hdr = harness::ported_header(&bytes[..cut]).expect("reference header shape");
        hdr.extend_from_slice(&bytes[cut..]);
        assert_eq!(i.compare(first, &hdr), Verdict::Equal);
        let mut bad = bytes.clone();
        let last = bad.len() - 1;
        bad[last] ^= 1;
        assert!(matches!(
            i.compare(first, &bad),
            Verdict::Differs { index: 0, .. }
        ));
        let mut one_off = produced.clone();
        one_off.insert(first.clone(), bad);
        assert!(!i.compare_all(&one_off).is_ok());
    }
}

#[cfg(unix)]
#[test]
fn self_private_directory_modes_symlinks_and_owner() {
    use harness::{dir_state, make_private_dir, DirState};
    use std::os::unix::fs::{MetadataExt, PermissionsExt};
    let t = TempDir::new("mode");
    let d = t.path().join("private");
    make_private_dir(&d).unwrap();
    let md = fs::metadata(&d).unwrap();
    assert_eq!(md.mode() & 0o777, 0o700);
    let me = md.uid();
    assert_eq!(dir_state(&d, Some(me)).unwrap(), DirState::Usable);
    assert_eq!(dir_state(&t.path().join("none"), Some(me)).unwrap(), DirState::Missing);
    // Group or other access: ours, to be replaced.
    fs::set_permissions(&d, fs::Permissions::from_mode(0o755)).unwrap();
    assert_eq!(dir_state(&d, Some(me)).unwrap(), DirState::WrongMode);
    // Another owner: refused. A symlink (even to a private directory) and a file: refused.
    fs::set_permissions(&d, fs::Permissions::from_mode(0o700)).unwrap();
    assert!(dir_state(&d, Some(me.wrapping_add(1))).is_err());
    let link = t.path().join("link");
    std::os::unix::fs::symlink(&d, &link).unwrap();
    assert!(dir_state(&link, Some(me)).is_err());
    let file = t.path().join("file");
    fs::write(&file, b"x").unwrap();
    assert!(dir_state(&file, Some(me)).is_err());
}

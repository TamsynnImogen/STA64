#!/usr/bin/env python3
"""Write the alpha testbed's switch-group child mods (docs/ALPHA_TESTBED.md).

    python3 tools/testbed/gen_children.py <testbed repo>
    python3 tools/testbed/gen_children.py --check
    python3 tools/testbed/gen_children.py --on <Group>   # the switches a group turns on

Each group becomes mods/STA64Testbed_<Group>/ with an info.ini whose
[Features] section names every switch in FEATURE_NAMES (crates/sta_content/
src/profile.rs): on for the group's switches and `cheats`, off for the rest.
Sandbox turns every switch on except a1_compat. `--check` only verifies that
every switch is in exactly one group (exit 1 otherwise).
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROFILE = os.path.join(REPO, "crates", "sta_content", "src", "profile.rs")

ALWAYS_ON = {"cheats"}
ALWAYS_OFF = {"a1_compat"}

GROUPS = {
    "Combat": ["weapon_damage_controls", "fire_arcs", "turrets", "team_change_weapons", "weapon_shot_timing",
               "start_fire_hold", "weapon_hit_roll", "weapon_target_damage", "weapon_target_masks",
               "weapon_cloak_fire", "crew_weapon_delay", "beam_damage_at_end"],
    "Defence": ["directional_shields", "point_defense_cycles", "pd_energy", "pd_debt_timer", "energy_systems",
                "shield_zero_hold", "crew_loss_on_hit"],
    "Behaviour": ["attack_buffer_roots", "attack_combat_speed", "attack_opportunity_fire", "builder_hold_fire",
                  "target_score", "idle_assist", "assist_high_autonomy_only", "assist_on_ally_fire",
                  "transport_attack_by_weld", "warp_gates"],
    "Economy": ["extra_resources", "officer_capacity", "pay_on_queue"],
    "Production": ["multi_yard_builds", "construction_rigs", "upgrade_pods", "hybrid_yards", "station_rotation"],
    "Fleet": ["breeders", "collective_xp", "squadrons", "wreckage", "craft_identity"],
}

DESCRIPTIONS = {
    "Combat": "weapons: damage controls, fire arcs, turrets, shot timing, hit rolls, target masks",
    "Defence": "shields and point defence: directional shields, PD cycles and energy, energy systems",
    "Behaviour": "unit AI: attack buffers, opportunity fire, target scoring, assist rules",
    "Economy": "resources, officers, pay on queue",
    "Production": "yards and building: multi-yard builds, construction rigs, upgrade pods, hybrid yards",
    "Fleet": "fleet systems: breeders, collective XP, squadrons, wreckage, craft identity",
    "Sandbox": "every system on at once",
}


def feature_names():
    text = open(PROFILE, encoding="utf-8").read()
    m = re.search(r"pub const FEATURE_NAMES: \[&str; (\d+)\] = \[(.*?)\];", text, re.S)
    names = re.findall(r'"([a-z0-9_]+)"', m.group(2))
    assert len(names) == int(m.group(1)), "FEATURE_NAMES length mismatch"
    return names


def check(names):
    seen = {}
    problems = []
    for g, members in GROUPS.items():
        for n in members:
            if n in seen:
                problems.append(f"{n}: in {seen[n]} and {g}")
            seen[n] = g
            if n not in names:
                problems.append(f"{n} ({g}): not a switch in FEATURE_NAMES")
    for n in names:
        if n not in seen and n not in ALWAYS_ON | ALWAYS_OFF:
            problems.append(f"{n}: in no group (add it to GROUPS in tools/testbed/gen_children.py)")
    return problems


def write(root, group, on, names, version):
    name = f"STA64Testbed_{group}"
    d = os.path.join(root, "mods", name)
    os.makedirs(d, exist_ok=True)
    lines = ["[Mod]", f"Name=STA64 Testbed: {group}", f"Description=STA64 closed alpha test mod: {DESCRIPTIONS[group]}.",
             "Author=Immy", f"Version={version}", "ParentMod=STA64Testbed", "", "[Features]"]
    lines += [f"{n}={1 if n in on else 0}" for n in names]
    with open(os.path.join(d, "info.ini"), "w", newline="\r\n") as f:
        f.write("; Generated by tools/testbed/gen_children.py in the STA64 repository; do not edit.\n")
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(d, "manifest.toml"), "w") as f:
        f.write(f'[mod]\nid = "sta64-testbed-{group.lower()}"\nname = "STA64 Testbed: {group}"\n'
                f'version = "{version}"\ndescription = "STA64 closed alpha test mod: {DESCRIPTIONS[group]}."\n'
                f'authors = ["Immy"]\nprofile = "native"\nkind = "addon"\n\n'
                f'[dependencies]\n"sta64-testbed" = "^{version}"\n')
    return name


def main():
    names = feature_names()
    problems = check(names)
    for p in problems:
        print("error:", p, file=sys.stderr)
    if problems:
        sys.exit(1)
    if sys.argv[1:2] == ["--on"]:
        g = sys.argv[2].removeprefix("STA64Testbed_")
        on = set(names) - ALWAYS_OFF if g == "Sandbox" else set(GROUPS[g]) | ALWAYS_ON
        print(" ".join(sorted(on)))
        return
    if sys.argv[1:] == ["--check"]:
        print(f"ok: {len(names)} switches, {len(GROUPS)} groups")
        return
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    base = open(os.path.join(root, "mods", "STA64Testbed", "manifest.toml")).read()
    version = re.search(r'version = "([^"]+)"', base).group(1)
    for g, members in GROUPS.items():
        print("wrote", write(root, g, set(members) | ALWAYS_ON, names, version))
    every = set(names) - ALWAYS_OFF
    print("wrote", write(root, "Sandbox", every, names, version))


if __name__ == "__main__":
    main()

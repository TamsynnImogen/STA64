#!/usr/bin/env python3
"""Inventory the MMM (Megadroid's Mission Mod) Lua API and its use.

Reads the luabind registrations in an MMM source checkout (names only: classes,
namespaces, methods, properties, enum values) and counts how often each name is
called by the installed mission scripts. Writes a Markdown report.

MMM (github.com/chreden/mmm) has no licence, so nothing of its code is copied:
this records the API surface STA64's integrated runtime must provide.

usage: mmm_inventory.py <mmm_source_dir> <out.md> <missions_dir> [<missions_dir> ...]
"""

import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

CLASS = re.compile(r'class_<\s*([^,>]+)[^>]*>\s*\(\s*"([^"]+)"\s*\)')
NAMESPACE = re.compile(r'namespace_\s*\(\s*"([^"]+)"\s*\)')
MODULE = re.compile(r'module\s*\(\s*[^,)]+(?:,\s*"([^"]+)")?\s*\)')
METHOD = re.compile(r'\.def\s*\(\s*"([^"]+)"')
FREE = re.compile(r'(?<![.\w])def\s*\(\s*"([^"]+)"')
PROP = re.compile(r'\.(?:property|def_readonly|def_readwrite)\s*\(\s*"([^"]+)"')
VALUE = re.compile(r'value\s*\(\s*"([^"]+)"')


def scan_bindings(root: Path):
    """{(file, scope): {"methods": set, "props": set, "values": set}}"""
    api = defaultdict(lambda: {"methods": set(), "props": set(), "values": set(), "free": set()})
    for f in sorted(root.rglob("*Binding*.cpp")) + sorted(root.rglob("Globals.cpp")):
        text = f.read_text(errors="replace")
        # Strip comments.
        text = re.sub(r"//[^\n]*", "", text)
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        events = []
        for rx, kind in ((CLASS, "class"), (NAMESPACE, "ns"), (METHOD, "method"), (FREE, "free"), (PROP, "prop"), (VALUE, "value")):
            for m in rx.finditer(text):
                name = m.group(2) if kind == "class" else m.group(1)
                events.append((m.start(), kind, name))
        events.sort()
        scope = "(global)"
        for _, kind, name in events:
            if kind in ("class", "ns"):
                scope = name
                api[(f.name, scope)]  # create
            elif kind == "method":
                api[(f.name, scope)]["methods"].add(name)
            elif kind == "free":
                api[(f.name, scope)]["free"].add(name)
            elif kind == "prop":
                api[(f.name, scope)]["props"].add(name)
            elif kind == "value":
                api[(f.name, scope)]["values"].add(name)
    return api


def scan_usage(dirs):
    calls = Counter()
    files = 0
    for d in dirs:
        for f in Path(d).rglob("*.lua"):
            files += 1
            text = f.read_text(errors="replace")
            text = re.sub(r"--\[\[.*?\]\]", "", text, flags=re.S)
            text = re.sub(r"--[^\n]*", "", text)
            # Method calls (obj:fn(), Ns.fn()) and property / enum access (obj.name).
            for m in re.finditer(r"[:.]\s*([A-Za-z_]\w*)", text):
                calls[m.group(1)] += 1
            for m in re.finditer(r"(?<![.:\w])([A-Z]\w*)\s*[.(]", text):
                calls[m.group(1)] += 1
    return calls, files


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(2)
    src, out, dirs = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3:]
    api = scan_bindings(src)
    calls, nfiles = scan_usage(dirs)

    all_names = set()
    for v in api.values():
        all_names |= v["methods"] | v["free"] | v["props"] | v["values"]
    used = {n: calls[n] for n in all_names if calls[n]}

    lines = [
        "# MMM Lua API inventory",
        "",
        "Generated by `tools/mmm_inventory.py` from MMM's luabind registrations",
        "(names only; MMM has no licence, so no code is copied) and from the",
        f"installed mission scripts ({nfiles} `.lua` files).",
        "",
        "This is the surface STA64's integrated MMM runtime must provide",
        "(see [MISSIONS.md](MISSIONS.md)). Counts are uses (calls, property and enum",
        "access) in the installed scripts; names never used there can wait. Short",
        "common names (`name`, `add`) also match unrelated Lua, so their counts run high.",
        "",
        "## Most used",
        "",
        "| Name | Calls |",
        "|---|---|",
    ]
    for name, n in sorted(used.items(), key=lambda kv: (-kv[1], kv[0]))[:80]:
        lines.append(f"| `{name}` | {n} |")
    lines += [
        "",
        f"{len(used)} of {len(all_names)} bound names are called by the installed scripts.",
        "",
        "## By binding",
        "",
    ]
    for (fname, scope), v in sorted(api.items()):
        names = sorted(v["methods"] | v["free"])
        if not (names or v["props"] or v["values"]):
            continue
        lines.append(f"### `{scope}` ({fname})")
        lines.append("")
        if names:
            lines.append("Functions: " + ", ".join(f"`{n}`" + (f" ({calls[n]})" if calls[n] else "") for n in names))
        if v["props"]:
            lines.append("")
            lines.append("Properties: " + ", ".join(f"`{n}`" + (f" ({calls[n]})" if calls[n] else "") for n in sorted(v["props"])))
        if v["values"]:
            lines.append("")
            lines.append("Values: " + ", ".join(f"`{n}`" + (f" ({calls[n]})" if calls[n] else "") for n in sorted(v["values"])))
        lines.append("")
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(api)} scopes, {len(all_names)} names, {len(used)} used in {nfiles} scripts -> {out}")


if __name__ == "__main__":
    main()
